import catalog from "../data/catalog-cards.json" with { type: "json" };
import corePlayers from "../data/core-player.json" with { type: "json" };
import { isTextBlank } from "./card-text.js";
import { playerOrder } from "./team.js";
import type {
  MutagenEnginePorts,
  MutagenForcedResponse,
} from "./mutagen-formula.js";
import type { ZzzaxIndirectRequest } from "./zzzax.js";
import type { Card, Effect, GameState, Option, Piece } from "./types.js";

const definitions = new Map(
  ([...catalog, ...corePlayers] as Card[]).map((c) => [c.code, c]),
);
const card = (p: Pick<Piece, "code">) => definitions.get(p.code)!;
const I = (name: string, args: Record<string, unknown> = {}): Effect => ({
  type: `ironspider-sinister:${name}`,
  ...args,
});
const need = (condition: unknown, message: string) => {
  if (!condition) throw Error(message);
};

/** Original eight faces and eight physical cards; no encounter aliases. */
export const IRONSPIDER_SINISTER_SCRIPT_CODES = [
  "31030",
  "31031",
  "31032",
  "31033",
  "31034",
  "31035",
  "31036",
  "31037",
] as const;
export const IRONSPIDER_SINISTER_SET = "ironspider_sinister";

export interface IronspiderSinisterCharacter {
  id: string;
  label: string;
  code?: string;
}
export interface IronspiderSinisterAllocation {
  target: string;
  amount: number;
}
export interface IronspiderSinisterPorts extends Pick<
  MutagenEnginePorts,
  | "queue"
  | "choose"
  | "pay"
  | "canPay"
  | "discardTop"
  | "putMinion"
  | "discardPiece"
  | "shuffleIntoEncounter"
> {
  /** Canonical native traits, including grants and current type changes. */
  hasTrait(s: GameState, id: string, trait: string): boolean;
  /** Current identity, in either form, and actual controlled allies. */
  controlledCharacters(s: GameState): IronspiderSinisterCharacter[];
  /** Current ATK, including attachments, reductions and other native grants.
   * This is evaluated when Hobgoblin replaces the would-attack occurrence. */
  enemyAttack(s: GameState, p: Piece): number;
  /** Move the actual hand card to the global attachment zone, preserving its
   * owner. Do not play, pay for, or resolve the player card's printed text. */
  attachHand(s: GameState, p: Piece, enemyId: string): void;
  /** All indirect packets use native assignment, prevention and simultaneous
   * defeat checks. Exhaust only recipients with actual positive damage. */
  indirect(
    s: GameState,
    request: ZzzaxIndirectRequest & { exhaustDamaged?: boolean },
  ): void;
  /** Damage from one actual Bombshell attack after its DEF/attack prevention.
   * Prepare every native per-character prevention window before committing
   * the whole allocation. Record the actual attack receipts; finish the same
   * attack and its response windows only after those packets have resolved.
   * This is ordinary attack damage, with no indirect remaining-HP ceiling. */
  attackDamage(
    s: GameState,
    request: {
      sourceId: string;
      playerId: string;
      allocations: IronspiderSinisterAllocation[];
      after?: Effect;
    },
  ): void;
}
type TraitPorts = Pick<IronspiderSinisterPorts, "hasTrait">;

function criminal(s: GameState, p: Piece, ports?: TraitPorts) {
  return (
    (card(p)?.type_code === "minion" || s.minions.some((q) => q.id === p.id)) &&
    (ports && s.minions.some((q) => q.id === p.id)
      ? ports.hasTrait(s, p.id, "Criminal")
      : (card(p).traits || "").split(/\.\s*/).includes("Criminal"))
  );
}
function criminals(s: GameState, ports?: TraitPorts) {
  return s.minions.filter((p) => criminal(s, p, ports));
}

/** This restriction applies to every removal effect, including copied or
 * unlabelled threat removal, and to criminals engaged with any other seat. */
export function ironspiderSinisterThwartBlocked(
  s: GameState,
  p: Piece,
  ports?: TraitPorts,
): boolean {
  return (
    p.code === "31030" &&
    s.sideSchemes.some((q) => q.id === p.id) &&
    !isTextBlank(s, p) &&
    criminals(s, ports).length > 0
  );
}

/** Traits are not blanked text. A blanked criminal still receives Surge from
 * an active environment. Multiple grants of the same keyword do not stack. */
export function ironspiderSinisterCriminalSurge(
  s: GameState,
  p: Piece,
  ports?: TraitPorts,
): boolean {
  return (
    criminal(s, p, ports) &&
    (s.environments || []).some((q) => q.code === "31037" && !isTextBlank(s, q))
  );
}

/** Every printed icon counts. An attached Energy resource card adds two HP;
 * resources generated by an ability or Haywire's hand-only replacement do
 * not change attached printed icons. Blanking does not detach those cards. */
export function ironspiderSinisterHealthBonus(s: GameState, p: Piece) {
  return p.code === "31032" && !isTextBlank(s, p)
    ? s.attachments
        .filter((q) => q.attachedTo === p.id)
        .reduce((n, q) => n + Number(card(q).resource_energy || 0), 0)
    : 0;
}

/** Native keyword readers already implement Guard, Patrol, Toughness and
 * Retaliate. Overkill is a constant on Iron Spider's actual attacks. */
export function ironspiderSinisterOverkill(s: GameState, p: Piece) {
  return p.code === "31034" && !isTextBlank(s, p);
}

/** Ordinary native entry supplies printed side-scheme threat and minion
 * engagement. Surge in Crime is moved to the environment zone by the host;
 * the ordinary reveal keyword scheduler supplies its one printed Surge. */
export function ironspiderSinisterReveal(
  _s: GameState,
  p: Piece,
): Effect[] | null {
  return IRONSPIDER_SINISTER_SCRIPT_CODES.includes(
    p.code as (typeof IRONSPIDER_SINISTER_SCRIPT_CODES)[number],
  )
    ? []
    : null;
}

/** Spot retains the actual boosted physical card. Other faces return their
 * boost effects and let native finishResolution discard the boost normally. */
export function ironspiderSinisterBoost(
  s: GameState,
  p: Piece,
  playerId = s.activePlayerId,
): { effects: Effect[]; retainsCard: boolean } | null {
  if (
    !IRONSPIDER_SINISTER_SCRIPT_CODES.includes(
      p.code as (typeof IRONSPIDER_SINISTER_SCRIPT_CODES)[number],
    )
  )
    return null;
  switch (p.code) {
    case "31031":
      return {
        effects: playerOrder(s).map((seat) =>
          I("bombshell-boost", {
            sourceId: p.id,
            playerId: seat.id,
            actorId: seat.id,
          }),
        ),
        retainsCard: false,
      };
    case "31035":
      return {
        effects: [I("discard-seven", { actorId: playerId })],
        retainsCard: false,
      };
    case "31036":
      return {
        effects: [I("spot-boost", { piece: p, actorId: playerId })],
        retainsCard: true,
      };
    default:
      return { effects: [], retainsCard: false };
  }
}

export function ironspiderSinisterEngagementResponses(
  s: GameState,
  p: Piece,
  playerId = s.activePlayerId,
): Effect[] {
  return p.code === "31032" && !isTextBlank(s, p)
    ? [I("electro", { id: p.id, actorId: playerId })]
    : [];
}
export function ironspiderSinisterActivationResponses(
  s: GameState,
  enemyId: string,
): MutagenForcedResponse[] {
  const p = s.minions.find((q) => q.id === enemyId && q.code === "31032");
  return p && !isTextBlank(s, p)
    ? [
        {
          id: `${p.id}:electro`,
          sourceId: p.id,
          title: "Electro",
          effects: [I("electro", { id: p.id, actorId: s.activePlayerId })],
        },
      ]
    : [];
}

/** Schedule after stun/Webbed Up cancellation, before attack initiation,
 * boosts or defense. It replaces the attack, rather than completing one. */
export function ironspiderSinisterAttackReplacement(
  s: GameState,
  p: Piece,
): Effect[] | null {
  return p.code === "31033" && !isTextBlank(s, p)
    ? [I("hobgoblin", { id: p.id, actorId: s.activePlayerId })]
    : null;
}

export function ironspiderSinisterAttackDamageReplacement(
  s: GameState,
  p: Piece,
  amount: number,
  after?: Effect,
): Effect[] | null {
  return p.code === "31031" && !isTextBlank(s, p)
    ? [
        I("bombshell", {
          sourceId: p.id,
          playerId: s.activePlayerId,
          amount: Math.max(0, amount),
          actorId: s.activePlayerId,
          after,
        }),
      ]
    : null;
}

/** FFG June 2023 ruling #17: Sandman must remain in play after damage;
 * lethal damage defeats him before his Forced Response can initiate. */
export function ironspiderSinisterDamageResponses(
  s: GameState,
  receipt: { piece: Piece; actualDamage: number; fromAttack: boolean },
): Effect[] {
  return receipt.piece.code === "31035" &&
    s.minions.some((p) => p.id === receipt.piece.id) &&
    receipt.fromAttack &&
    receipt.actualDamage > 0 &&
    !isTextBlank(s, receipt.piece)
    ? [I("discard-seven", { actorId: s.activePlayerId })]
    : [];
}

/** Queue through the native minion When Defeated window. The actual source
 * is retained even after normal physical defeat cleanup puts it in discard. */
export function ironspiderSinisterDefeatResponses(
  s: GameState,
  p: Piece,
  excessDamage: number,
): Effect[] {
  return p.code === "31036" && excessDamage <= 0 && !isTextBlank(s, p)
    ? [I("spot-shuffle", { piece: p, actorId: s.activePlayerId })]
    : [];
}

export function ironspiderSinisterActions(
  s: GameState,
  p: Piece,
  ports: Pick<IronspiderSinisterPorts, "canPay" | "hasTrait">,
): Option[] {
  return p.code === "31037" &&
    (s.environments || []).some((q) => q.id === p.id) &&
    !isTextBlank(s, p) &&
    s.player.form === "hero" &&
    !criminals(s, ports).length &&
    ports.canPay(s, 2, [])
    ? [
        {
          id: "ironspider-sinister-remove",
          label: "Spend 2 resources → discard Surge in Crime",
          image: p.code,
          effects: [I("remove-pay", { id: p.id, actorId: s.activePlayerId })],
        },
      ]
    : [];
}
export function ironspiderSinisterActionEffects(
  s: GameState,
  p: Piece,
  action: string,
  ports: Pick<IronspiderSinisterPorts, "canPay" | "hasTrait">,
): Effect[] | null {
  const option = ironspiderSinisterActions(s, p, ports).find(
    (q) => q.id === action,
  );
  return option ? option.effects : null;
}

function discard(s: GameState, amount: number, ports: IronspiderSinisterPorts) {
  let boost = 0;
  for (let n = 0; n < amount; n++) {
    const result = ports.discardTop(s);
    if (result.piece) boost += Number(card(result.piece).boost || 0);
    // RRG discard-top-X stops at the first exhaustion boundary, even when
    // the host immediately shuffles the discard and resets the native deck.
    if (!result.piece || result.emptied) break;
  }
  return boost;
}

export function resolveIronspiderSinisterEffect(
  s: GameState,
  e: Effect,
  ports: IronspiderSinisterPorts,
): boolean {
  if (!e.type.startsWith("ironspider-sinister:")) return false;
  switch (e.type) {
    case "ironspider-sinister:electro": {
      const enemy = s.minions.find((p) => p.id === e.id && p.code === "31032");
      if (!enemy || isTextBlank(s, enemy)) break;
      const options = s.player.hand
        .filter((p) => Number(card(p).resource_energy || 0) > 0)
        .map((p): Option => ({
          id: p.id,
          label: card(p).name,
          image: p.code,
          detail: `${card(p).resource_energy} printed Energy resource${card(p).resource_energy === 1 ? "" : "s"}`,
          effects: [
            I("electro-attach", {
              enemyId: enemy.id,
              id: p.id,
              actorId: s.activePlayerId,
            }),
          ],
        }));
      if (options.length)
        ports.choose(
          s,
          "Electro · Forced Response",
          "Attach one card from your hand with a printed Energy resource.",
          options,
        );
      break;
    }
    case "ironspider-sinister:electro-attach": {
      const enemy = s.minions.find(
        (p) => p.id === e.enemyId && p.code === "31032",
      );
      const p = s.player.hand.find((p) => p.id === e.id);
      need(
        enemy && p && Number(card(p).resource_energy || 0) > 0,
        "Choose an actual hand card with a printed Energy resource.",
      );
      ports.attachHand(s, p!, enemy!.id);
      break;
    }
    case "ironspider-sinister:hobgoblin": {
      const enemy = s.minions.find((p) => p.id === e.id && p.code === "31033");
      if (!enemy || isTextBlank(s, enemy)) break;
      const amount = discard(
        s,
        Math.max(0, ports.enemyAttack(s, enemy)),
        ports,
      );
      if (amount)
        ports.indirect(s, {
          playerId: s.activePlayerId,
          amount,
          sourceId: enemy.id,
          sourceTitle: "Hobgoblin",
        });
      break;
    }
    case "ironspider-sinister:discard-seven":
      discard(s, 7, ports);
      break;
    case "ironspider-sinister:spot-boost":
      ports.putMinion(s, e.piece, s.activePlayerId);
      break;
    case "ironspider-sinister:spot-shuffle":
      ports.shuffleIntoEncounter(s, e.piece);
      break;
    case "ironspider-sinister:bombshell-boost":
      ports.indirect(s, {
        playerId: e.playerId,
        amount: 1,
        sourceId: e.sourceId,
        sourceTitle: "Bombshell · Boost",
        exhaustDamaged: true,
      });
      break;
    case "ironspider-sinister:bombshell": {
      const characters = ports.controlledCharacters(s);
      const base = characters.length
        ? Math.floor(e.amount / characters.length)
        : 0;
      const allocations = characters.map((p) => ({
        target: p.id,
        amount: base,
      }));
      ports.queue(
        s,
        I("bombshell-remainder", {
          ...e,
          type: "ironspider-sinister:bombshell-remainder",
          characters,
          allocations,
          remaining: characters.length ? e.amount % characters.length : 0,
          selected: [],
        }),
      );
      break;
    }
    case "ironspider-sinister:bombshell-remainder": {
      if (!e.remaining) {
        ports.attackDamage(s, {
          sourceId: e.sourceId,
          playerId: e.playerId,
          allocations: e.allocations,
          after: e.after,
        });
        break;
      }
      const options = (e.characters as IronspiderSinisterCharacter[])
        .filter((p) => !e.selected.includes(p.id))
        .map((p): Option => ({
          id: p.id,
          label: p.label,
          image: p.code,
          effects: [
            {
              ...e,
              allocations: (
                e.allocations as IronspiderSinisterAllocation[]
              ).map((q) =>
                q.target === p.id ? { ...q, amount: q.amount + 1 } : q,
              ),
              selected: [...e.selected, p.id],
              remaining: e.remaining - 1,
            },
          ],
        }));
      if (options.length === e.remaining)
        ports.queue(s, {
          ...e,
          remaining: 0,
          allocations: (e.allocations as IronspiderSinisterAllocation[]).map(
            (q) =>
              e.selected.includes(q.target)
                ? q
                : { ...q, amount: q.amount + 1 },
          ),
        });
      else
        ports.choose(
          s,
          "Bombshell · divide attack damage",
          `Divide ${e.amount} attack damage as evenly as possible among all ${e.characters.length} controlled characters. Choose ${e.remaining} character${e.remaining === 1 ? "" : "s"} to take one additional damage.`,
          options,
        );
      break;
    }
    case "ironspider-sinister:remove-pay": {
      const p = (s.environments || []).find((p) => p.id === e.id);
      need(
        p && ironspiderSinisterActions(s, p, ports).length,
        "Surge in Crime can only be removed by a hero when no Criminal minion is in play.",
      );
      ports.pay(
        s,
        2,
        [],
        [I("remove-paid", { id: p!.id, actorId: s.activePlayerId })],
        "Surge in Crime",
        true,
      );
      break;
    }
    case "ironspider-sinister:remove-paid": {
      const p = (s.environments || []).find((p) => p.id === e.id);
      need(
        p && p.code === "31037" && !criminals(s, ports).length,
        "The actual environment can no longer be removed.",
      );
      ports.discardPiece(s, p!.id);
      break;
    }
    default:
      throw Error(`Unknown Iron Spider's Sinister Six effect: ${e.type}`);
  }
  return true;
}
